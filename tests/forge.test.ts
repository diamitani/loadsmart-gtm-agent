import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { parse, stringify } from "yaml";
import { renderBuild, validateAgent } from "@/forge/build";
import { AgentSpec } from "@/forge/schema";
import { architectTools } from "@/lib/agent/tools";
import { sdrTools } from "@/lib/connectors/sdr-tools";
import { AGENT_SLUG, systemInstructions } from "@/lib/agent/skills";
import { agentManifest } from "@/lib/agent/manifest";

const root = process.cwd();
const tools = Object.entries({ ...architectTools({}), ...sdrTools() }).map(([name, t]) => ({ name, needsApproval: (t as { needsApproval?: unknown }).needsApproval === true }));
const spec = () => parse(fs.readFileSync(`agents/${AGENT_SLUG}/agent.yaml`, "utf8"));

/** Validate a modified copy of the spec in a temp repo that links to the real agent/ folder. */
function validateVariant(mut: (s: Record<string, any>) => void, toolList = tools) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "forge-"));
  for (const d of ["agent", "docs"]) fs.symlinkSync(path.join(root, d), path.join(tmp, d));
  fs.mkdirSync(path.join(tmp, "agents", AGENT_SLUG), { recursive: true });
  const s = spec();
  mut(s);
  fs.writeFileSync(path.join(tmp, "agents", AGENT_SLUG, "agent.yaml"), stringify(s));
  return validateAgent(tmp, AGENT_SLUG, toolList);
}

describe("forge: enably-gtm-architect spec", () => {
  it("validates against the master schema and this repo", () => {
    const v = validateAgent(root, AGENT_SLUG, tools);
    expect(v.errors).toEqual([]);
  });

  it("committed build/ is current, and the runtime injects the generated system prompt", () => {
    const v = validateAgent(root, AGENT_SLUG, tools);
    const files = renderBuild(root, v.spec!, v.sourceHash!);
    for (const [name, text] of Object.entries(files)) expect(fs.readFileSync(`build/${AGENT_SLUG}/${name}`, "utf8"), name).toBe(text);
    const soul = systemInstructions();
    expect(soul).toContain(fs.readFileSync("agent/instructions/system.md", "utf8").trim().slice(0, 300));
    expect(soul).toContain("## Agent contract (from the spec)");
    expect(soul).toContain("offer, icp, deliverable");
    expect(soul).not.toContain("GENERATED by forge");
    expect(agentManifest().forge.build).toBe("current");
  });

  it("every approval-gated tool in code is declared in the spec, and vice versa", () => {
    const gated = tools.filter((t) => t.needsApproval).map((t) => t.name).sort();
    expect(gated).toEqual([...spec().x_enably.approval_tools].sort());
    expect(gated).toContain("send_email");
  });

  it("rejects specs that break the template rules", () => {
    expect(validateVariant((s) => (s.acceptance_tests = s.acceptance_tests.filter((t: { name: string }) => !/missing/.test(t.name)))).errors.join()).toMatch(/missing input test/);
    expect(validateVariant((s) => (s.identity.slug = "Bad Slug")).ok).toBe(false);
    expect(validateVariant((s) => (s.model.default_tier = "free")).errors.join()).toMatch(/high data sensitivity/);
    expect(validateVariant((s) => s.tools.skills.push("no-such-skill")).errors.join()).toMatch(/no-such-skill/);
    expect(validateVariant((s) => s.tools.sub_agents.push("ghost-agent")).errors.join()).toMatch(/not a forge agent/);
    // a send tool that silently lost its approval gate is caught
    const ungated = tools.map((t) => (t.name === "send_email" ? { ...t, needsApproval: false } : t));
    expect(validateVariant(() => undefined, ungated).errors.join()).toMatch(/send_email' does not pause for approval/);
  });

  it("the schema itself parses the template defaults", () => {
    expect(AgentSpec.safeParse(spec()).success).toBe(true);
  });
});
