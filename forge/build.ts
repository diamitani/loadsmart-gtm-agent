/**
 * Agent Forge — validate a spec against the schema AND this repo (skills, tools, approvals),
 * then generate build/<slug>/: system_prompt.md, covenant.md, agent.json, agent-card.json, SKILL.md.
 * Pure functions over the file system; deterministic output (no timestamps) so CI can diff it.
 */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { parse } from "yaml";
import { AgentSpec, formatIssues } from "./schema";

export interface ImplementedTool {
  name: string;
  needsApproval: boolean;
}

export interface ValidateResult {
  ok: boolean;
  errors: string[];
  spec?: AgentSpec;
  sourceHash?: string;
}

export const specPath = (root: string, slug: string) => path.join(root, "agents", slug, "agent.yaml");
export const buildDir = (root: string, slug: string) => path.join(root, "build", slug);

/** sha256 over the spec + soul, so the runtime can tell when build/ is stale. */
export function sourceHash(root: string, slug: string, spec?: AgentSpec): string {
  const h = createHash("sha256").update(fs.readFileSync(specPath(root, slug), "utf8"));
  if (spec?.x_enably?.soul) h.update(readOr(path.join(root, spec.x_enably.soul)));
  return h.digest("hex").slice(0, 16);
}

/** `runtime: true` skips checks on files that are not bundled into serverless functions (docs/); CI runs the full check. */
export function validateAgent(root: string, slug: string, tools: ImplementedTool[], opts: { runtime?: boolean } = {}): ValidateResult {
  const file = specPath(root, slug);
  if (!fs.existsSync(file)) return { ok: false, errors: [`${path.relative(root, file)} not found`] };
  let raw: unknown;
  try {
    raw = parse(fs.readFileSync(file, "utf8"));
  } catch (err) {
    return { ok: false, errors: [`YAML: ${(err as Error).message}`] };
  }
  const parsed = AgentSpec.safeParse(raw);
  if (!parsed.success) return { ok: false, errors: formatIssues(parsed.error) };
  const spec = parsed.data;
  const errors: string[] = [];
  if (spec.identity.slug !== slug) errors.push(`identity.slug '${spec.identity.slug}' must match the folder '${slug}'`);

  for (const s of spec.tools.skills) if (!fs.existsSync(path.join(root, "agent", "skills", s, "SKILL.md"))) errors.push(`tools.skills: '${s}' has no agent/skills/${s}/SKILL.md`);
  for (const w of spec.tools.workflows) if (!fs.existsSync(path.join(root, "agent", "workflows", `${w}.json`))) errors.push(`tools.workflows: '${w}' has no agent/workflows/${w}.json`);
  for (const s of spec.tools.sub_agents) if (!fs.existsSync(specPath(root, s))) errors.push(`tools.sub_agents: '${s}' is not a forge agent (agents/${s}/agent.yaml)`);
  for (const r of [...spec.knowledge.references, ...(opts.runtime ? [] : spec.knowledge.documentation)]) if (!fs.existsSync(path.join(root, r))) errors.push(`knowledge: '${r}' not found`);

  const x = spec.x_enably;
  if (x) {
    if (!fs.existsSync(path.join(root, x.soul))) errors.push(`x_enably.soul: '${x.soul}' not found`);
    if (!fs.existsSync(path.join(root, x.subagents))) errors.push(`x_enably.subagents: '${x.subagents}' not found`);
    const byName = new Map(tools.map((t) => [t.name, t]));
    for (const t of x.approval_tools) {
      const impl = byName.get(t);
      if (!impl) errors.push(`x_enably.approval_tools: '${t}' is not implemented`);
      else if (!impl.needsApproval) errors.push(`x_enably.approval_tools: '${t}' does not pause for approval in code`);
    }
    for (const t of tools) if (t.needsApproval && !x.approval_tools.includes(t.name)) errors.push(`tool '${t.name}' is approval-gated in code but not listed in x_enably.approval_tools`);
    for (const t of x.removed_tools) if (byName.has(t)) errors.push(`x_enably.removed_tools: '${t}' is still exposed to the model`);
  }
  return { ok: errors.length === 0, errors, spec, sourceHash: sourceHash(root, slug, spec) };
}

const list = (xs: string[]) => (xs.length ? xs.map((x) => `- ${x}`).join("\n") : "- (none)");

export function renderBuild(root: string, spec: AgentSpec, hash: string): Record<string, string> {
  const soul = spec.x_enably ? readOr(path.join(root, spec.x_enably.soul)).trim() : "";
  const id = spec.identity;
  const header = `<!-- GENERATED by forge from agents/${id.slug}/agent.yaml (source ${hash}). Do not edit — change the spec and run npm run forge:build. -->`;

  const contract = [
    "## Agent contract (from the spec)",
    `- Job: ${spec.overview.function}`,
    `- Objective: ${spec.overview.objective}`,
    `- Voice: ${id.voice}`,
    `- Inputs required before acting (wholeness gate, W = present ÷ required must be 1.00): ${spec.guardrails.foundation_required.join(", ") || "none"}`,
    "",
    "### Never do",
    list(spec.guardrails.hard_stops),
    "",
    "### Ask for approval first (the runtime enforces this with Approve / Deny)",
    list(spec.guardrails.confirm_first),
    "",
    "### Do on your own",
    list(spec.guardrails.autonomous),
    "",
    "### Stop and ask when",
    list(spec.guardrails.abort_conditions),
    "",
    "### Verify before presenting as fact",
    list(spec.guardrails.truth_guard_categories),
  ].join("\n");

  const systemPrompt = [header, soul, contract].filter(Boolean).join("\n\n") + "\n";

  const covenant = [
    header,
    `# Covenant — ${id.name} v${id.version}`,
    "",
    `> ${id.tagline}`,
    "",
    "## Overview",
    `**Function.** ${spec.overview.function}`,
    "",
    spec.overview.description.trim(),
    "",
    `**Objective.** ${spec.overview.objective}`,
    `**Core user.** ${spec.overview.core_user}`,
    `**Stakeholders.** ${spec.overview.stakeholders.join(", ") || "—"}`,
    `**Outputs.** ${spec.overview.intended_outputs.join(", ")}`,
    "",
    "**Jobs to be done**",
    list(spec.overview.jobs_to_be_done),
    "",
    "## Capabilities",
    ...spec.capabilities.flatMap((c) => [`### ${c.id}`, c.description, "", ...c.workflow_steps.map((s, i) => `${i + 1}. ${s}`), "", c.guardrails.length ? `Guardrails: ${c.guardrails.join("; ")}` : "", ""]),
    "## Tools",
    `- Built-in: ${spec.tools.builtin.join(", ") || "—"}`,
    `- Integrations: ${spec.tools.integrations.join(", ") || "—"}`,
    `- MCP servers: ${spec.tools.mcp_servers.join(", ") || "configured per deployment"}`,
    `- Sub-agents: ${spec.tools.sub_agents.join(", ") || "—"}`,
    `- Skills: ${spec.tools.skills.join(", ")}`,
    spec.x_enably ? `- Approval-gated tools: ${spec.x_enably.approval_tools.join(", ")}` : "",
    "",
    "## Knowledge, state, runtime",
    `- RAG: ${spec.knowledge.rag.enabled ? `on (${spec.knowledge.rag.store}, top ${spec.knowledge.rag.top_k})` : "off"}`,
    `- Storage: ${spec.state.storage.provider}${spec.state.storage.per_user ? ", per user" : ""}, ${spec.state.storage.max_mb_per_user} MB/user`,
    `- Runtime: ${spec.runtime.targets.join(" + ")} · profile ${spec.runtime.profile} · max ${spec.runtime.max_steps} steps · channels ${spec.runtime.channels.join(", ")}`,
    `- Model: default ${spec.model.default_tier} (${spec.model[spec.model.default_tier].model}) · data sensitivity ${spec.model.data_sensitivity}`,
    "",
    "## Guardrails",
    contract.split("\n").slice(6).join("\n"),
    "",
    "## Billing & KPI",
    `- Billing: ${spec.billing.mode} · ${spec.billing.free_runs_per_day} free runs/day · ~${spec.billing.est_credits_per_run} credit/run · ${spec.billing.rate_limit_per_hour}/hour`,
    `- North star: ${spec.kpi.north_star} (owner ${spec.kpi.pnl_owner})`,
    "",
    "## Acceptance tests",
    ...spec.acceptance_tests.map((t) => `- **${t.name}** — “${t.input}” → ${t.expect.join("; ")}`),
    "",
  ].join("\n");

  const agentJson = { ...spec, build: { sourceHash: hash, generator: "forge@1" } };
  const card = {
    protocol: "a2a",
    name: id.name,
    description: spec.overview.function,
    version: id.version,
    url: `/api/agents/${id.slug}`,
    capabilities: { streaming: true, pushNotifications: false },
    skills: spec.capabilities.map((c) => ({ id: c.id, name: c.id, description: c.description })),
    defaultInputModes: ["text"],
    defaultOutputModes: ["text"],
    note: "Discovery only — the A2A call endpoint is not built.",
  };
  const skill = [
    "---",
    `name: ${id.slug}`,
    `description: ${spec.overview.function}`,
    "---",
    "",
    systemPrompt.replace(header, "").trim(),
    "",
  ].join("\n");

  return {
    "system_prompt.md": systemPrompt,
    "covenant.md": covenant,
    "agent.json": JSON.stringify(agentJson, null, 2) + "\n",
    "agent-card.json": JSON.stringify(card, null, 2) + "\n",
    "SKILL.md": skill,
  };
}

export function writeBuild(root: string, slug: string, files: Record<string, string>) {
  const dir = buildDir(root, slug);
  fs.mkdirSync(dir, { recursive: true });
  for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(dir, name), text);
}

function readOr(p: string): string {
  try {
    return fs.readFileSync(p, "utf8");
  } catch {
    return "";
  }
}
